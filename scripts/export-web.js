// Copies the compiled contracts the deploy page needs into web/contracts.js.
// Run after `npx hardhat compile`:  node scripts/export-web.js
const fs = require("fs");
const path = require("path");

const pick = (file, name) => {
  const a = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", "contracts", file, name + ".json"), "utf8"));
  return { abi: a.abi, bytecode: a.bytecode };
};
const out = {
  LaunchpadFactory: pick("LaunchpadFactory.sol", "LaunchpadFactory"),
  MockStable: pick("mocks/MockStable.sol", "MockStable"),
  MockRouter: pick("mocks/MockRouter.sol", "MockRouter"),
};
const file = path.join(__dirname, "..", "web", "contracts.js");
fs.writeFileSync(file, "// Generated by scripts/export-web.js from the compiled contracts. Do not edit by hand.\nwindow.JISR_ARTIFACTS = " + JSON.stringify(out) + ";\n");
console.log("Wrote web/contracts.js (" + Math.round(fs.statSync(file).size / 1024) + " KB)");
